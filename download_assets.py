def download_font(url, output_path):
    """下载字体文件"""
    try:
        headers = {
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'
        }
        request = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(request, context=ssl_context, timeout=30) as response:
            with open(output_path, 'wb') as f:
                f.write(response.read())
        return True
    except Exception as e:
        print(f"Error downloading {url}: {e}")
        return False

def main():
    fonts_dir = "d:\\AIWorkspaces\\nav-static-ui-pro-max\\assets\\fonts"

    # 下载Inter字体
    print("Downloading Inter fonts...")
    for unicode_range, filename in inter_fonts:
        url = f"{FONT_BASE_URL}{filename}"
        output_path = os.path.join(fonts_dir, filename)
        if os.path.exists(output_path):
            print(f"  {filename} already exists, skipping...")
            continue
        print(f"  Downloading {filename}...")
        if download_font(url, output_path):
            print(f"    ✓ Downloaded successfully")
        else:
            print(f"    ✗ Failed to download")

    print("\nFont download complete!")

if __name__ == "__main__":
    main()
